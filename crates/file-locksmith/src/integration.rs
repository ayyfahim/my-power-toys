//! File-manager context-menu integration (the Linux counterpart of the
//! upstream Explorer "Unlock with File Locksmith" entry).
//!
//! - Nautilus: `~/.local/share/nautilus/scripts/File Locksmith`
//! - Dolphin:  `~/.local/share/kio/servicemenus/mpt-file-locksmith.desktop`
//! - Thunar:   an `<action>` block in `~/.config/Thunar/uca.xml`

use anyhow::{Context, Result};
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use tracing::{info, warn};

pub const MENU_LABEL: &str = "Unlock with File Locksmith";
const THUNAR_UNIQUE_ID: &str = "mpt-file-locksmith";
const MARKER: &str = "Generated by MyPowerToys File Locksmith";

/// Paths of the integration files.
#[derive(Debug, Clone)]
pub struct IntegrationPaths {
    pub nautilus_script: PathBuf,
    pub dolphin_service_menu: PathBuf,
    pub thunar_uca: PathBuf,
}

impl IntegrationPaths {
    /// Paths under the given XDG data and config directories.
    pub fn new(data_dir: &Path, config_dir: &Path) -> Self {
        Self {
            nautilus_script: data_dir.join("nautilus/scripts/File Locksmith"),
            dolphin_service_menu: data_dir.join("kio/servicemenus/mpt-file-locksmith.desktop"),
            thunar_uca: config_dir.join("Thunar/uca.xml"),
        }
    }

    pub fn user() -> Result<Self> {
        let data = dirs::data_dir().context("could not determine data directory")?;
        let config = dirs::config_dir().context("could not determine config directory")?;
        Ok(Self::new(&data, &config))
    }
}

/// Quote a string for POSIX shells.
pub fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// Quote an argument for a desktop-entry `Exec=` key.
pub fn desktop_exec_quote(s: &str) -> String {
    let needs = s
        .chars()
        .any(|c| c.is_whitespace() || "\"'\\><~|&;$*?#()`".contains(c));
    if !needs {
        return s.to_string();
    }
    let mut out = String::from("\"");
    for c in s.chars() {
        if matches!(c, '"' | '`' | '$' | '\\') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('"');
    // In a .desktop value a backslash itself must be escaped once more.
    out.replace('\\', "\\\\")
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// Nautilus script. Nautilus sets `NAUTILUS_SCRIPT_SELECTED_FILE_PATHS`
/// (newline separated) for local files; fall back to the arguments.
pub fn nautilus_script(bin: &str) -> String {
    let bin = shell_quote(bin);
    format!(
        "#!/bin/sh\n\
         # {MARKER}\n\
         if [ -n \"$NAUTILUS_SCRIPT_SELECTED_FILE_PATHS\" ]; then\n\
         \tIFS='\n'\n\
         \tset -f\n\
         \texec {bin} $NAUTILUS_SCRIPT_SELECTED_FILE_PATHS\n\
         fi\n\
         exec {bin} \"$@\"\n"
    )
}

/// Dolphin / KDE service menu.
pub fn dolphin_service_menu(bin: &str) -> String {
    let exec = desktop_exec_quote(bin);
    format!(
        "# {MARKER}\n\
         [Desktop Entry]\n\
         Type=Service\n\
         MimeType=all/all;\n\
         X-KDE-ServiceTypes=KonqPopupMenu/Plugin\n\
         X-KDE-Priority=TopLevel\n\
         Actions=fileLocksmith;\n\
         \n\
         [Desktop Action fileLocksmith]\n\
         Name={MENU_LABEL}\n\
         Icon=system-lock-screen\n\
         Exec={exec} %F\n"
    )
}

/// Thunar custom action `<action>` block.
pub fn thunar_action(bin: &str) -> String {
    let command = xml_escape(&format!("{} %F", shell_quote(bin)));
    format!(
        "<action>\n\
         \t<icon>system-lock-screen</icon>\n\
         \t<name>{MENU_LABEL}</name>\n\
         \t<unique-id>{THUNAR_UNIQUE_ID}</unique-id>\n\
         \t<command>{command}</command>\n\
         \t<description>Find processes using the selected files</description>\n\
         \t<patterns>*</patterns>\n\
         \t<startup-notify/>\n\
         \t<directories/>\n\
         \t<audio-files/>\n\
         \t<image-files/>\n\
         \t<other-files/>\n\
         \t<text-files/>\n\
         \t<video-files/>\n\
         </action>\n"
    )
}

/// Byte range of our `<action>` block in a uca.xml document.
fn find_thunar_action(xml: &str) -> Option<std::ops::Range<usize>> {
    let id = format!("<unique-id>{THUNAR_UNIQUE_ID}</unique-id>");
    let at = xml.find(&id)?;
    let start = xml[..at].rfind("<action>")?;
    let end = at + xml[at..].find("</action>")? + "</action>".len();
    // Swallow the following newline so repeated install/uninstall is stable.
    let end = if xml[end..].starts_with('\n') {
        end + 1
    } else {
        end
    };
    Some(start..end)
}

/// Insert (or replace) our action in a uca.xml document. `None` means a new
/// file. Returns `None` if the existing document is not recognisable, so we
/// never overwrite a user's file we can't parse.
pub fn thunar_insert(existing: Option<&str>, bin: &str) -> Option<String> {
    let action = thunar_action(bin);
    let base = match existing {
        Some(x) if x.contains("</actions>") => thunar_remove(x),
        Some(x) if !x.trim().is_empty() => return None,
        _ => "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<actions>\n</actions>\n".to_string(),
    };
    let idx = base.rfind("</actions>").unwrap_or(base.len());
    let mut out = String::with_capacity(base.len() + action.len());
    out.push_str(&base[..idx]);
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out.push_str(&action);
    out.push_str(&base[idx..]);
    Some(out)
}

/// Remove our action from a uca.xml document (no-op if absent).
pub fn thunar_remove(xml: &str) -> String {
    match find_thunar_action(xml) {
        Some(r) => format!("{}{}", &xml[..r.start], &xml[r.end..]),
        None => xml.to_string(),
    }
}

fn write_executable(path: &Path, contents: &str) -> Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(path, contents).with_context(|| format!("failed to write {}", path.display()))?;
    fs::set_permissions(path, fs::Permissions::from_mode(0o755))?;
    Ok(())
}

/// Remove a generated file, but only if it carries our marker.
fn remove_generated(path: &Path) {
    match fs::read_to_string(path) {
        Ok(s) if s.contains(MARKER) => {
            if let Err(e) = fs::remove_file(path) {
                warn!("File Locksmith: failed to remove {}: {e}", path.display());
            }
        }
        Ok(_) => warn!(
            "File Locksmith: {} was not generated by us, leaving it",
            path.display()
        ),
        Err(_) => {}
    }
}

/// Install into the given locations, launching `bin`.
pub fn install_to(paths: &IntegrationPaths, bin: &str) -> Result<()> {
    write_executable(&paths.nautilus_script, &nautilus_script(bin))?;
    // KF6 requires local service menus to be executable.
    write_executable(&paths.dolphin_service_menu, &dolphin_service_menu(bin))?;

    let existing = fs::read_to_string(&paths.thunar_uca).ok();
    match thunar_insert(existing.as_deref(), bin) {
        Some(updated) if existing.as_deref() != Some(updated.as_str()) => {
            if let Some(dir) = paths.thunar_uca.parent() {
                fs::create_dir_all(dir)?;
            }
            fs::write(&paths.thunar_uca, updated)
                .with_context(|| format!("failed to write {}", paths.thunar_uca.display()))?;
        }
        Some(_) => {}
        None => warn!(
            "File Locksmith: {} has no </actions> element, skipping Thunar integration",
            paths.thunar_uca.display()
        ),
    }
    Ok(())
}

/// Remove from the given locations.
pub fn uninstall_from(paths: &IntegrationPaths) -> Result<()> {
    remove_generated(&paths.nautilus_script);
    remove_generated(&paths.dolphin_service_menu);
    if let Ok(existing) = fs::read_to_string(&paths.thunar_uca) {
        let updated = thunar_remove(&existing);
        if updated != existing {
            fs::write(&paths.thunar_uca, updated)
                .with_context(|| format!("failed to write {}", paths.thunar_uca.display()))?;
        }
    }
    Ok(())
}

/// Install the Nautilus, Dolphin and Thunar context-menu entries for the
/// current user.
pub fn install_file_manager_integration() -> Result<()> {
    let bin = crate::find_gui_binary();
    let paths = IntegrationPaths::user()?;
    install_to(&paths, &bin.to_string_lossy())?;
    info!("File Locksmith: file manager integration installed");
    Ok(())
}

/// Remove the context-menu entries installed by
/// [`install_file_manager_integration`].
pub fn uninstall_file_manager_integration() -> Result<()> {
    let paths = IntegrationPaths::user()?;
    uninstall_from(&paths)?;
    info!("File Locksmith: file manager integration removed");
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting() {
        assert_eq!(shell_quote("/usr/bin/x"), "'/usr/bin/x'");
        assert_eq!(shell_quote("it's"), r"'it'\''s'");
        assert_eq!(desktop_exec_quote("/usr/bin/x"), "/usr/bin/x");
        assert_eq!(desktop_exec_quote("/opt/my app/x"), "\"/opt/my app/x\"");
        assert_eq!(desktop_exec_quote("/a b/$x"), "\"/a b/\\\\$x\"");
    }

    #[test]
    fn generated_files_reference_binary() {
        assert!(nautilus_script("/b/mpt").contains("exec '/b/mpt' \"$@\""));
        assert!(dolphin_service_menu("/b/mpt").contains("Exec=/b/mpt %F"));
        assert!(thunar_action("/b/mpt").contains("<command>'/b/mpt' %F</command>"));
    }

    #[test]
    fn thunar_insert_and_remove() {
        let user = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<actions>\n<action>\n\t<name>Mine</name>\n\t<unique-id>1-2</unique-id>\n</action>\n</actions>\n";
        let with = thunar_insert(Some(user), "/b/mpt").unwrap();
        assert!(with.contains("<name>Mine</name>"));
        assert!(with.contains(THUNAR_UNIQUE_ID));
        assert!(with.trim_end().ends_with("</actions>"));
        // Re-installing does not duplicate.
        let again = thunar_insert(Some(&with), "/b/mpt").unwrap();
        assert_eq!(again, with);
        assert_eq!(again.matches(THUNAR_UNIQUE_ID).count(), 1);
        // Removing restores the original document.
        assert_eq!(thunar_remove(&with), user);

        let fresh = thunar_insert(None, "/b/mpt").unwrap();
        assert!(thunar_insert(Some("not xml"), "/b/mpt").is_none());
        assert!(fresh.starts_with("<?xml"));
        assert!(fresh.contains(THUNAR_UNIQUE_ID));
    }

    #[test]
    fn install_uninstall_roundtrip() {
        let root = std::env::temp_dir().join(format!("mpt-fl-integ-{}", std::process::id()));
        let _ = fs::remove_dir_all(&root);
        let paths = IntegrationPaths::new(&root.join("data"), &root.join("config"));
        install_to(&paths, "/b/mpt").unwrap();
        assert!(paths.nautilus_script.exists());
        assert!(paths.dolphin_service_menu.exists());
        let mode = fs::metadata(&paths.nautilus_script)
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o111, 0o111);
        assert!(
            fs::read_to_string(&paths.thunar_uca)
                .unwrap()
                .contains(THUNAR_UNIQUE_ID)
        );
        uninstall_from(&paths).unwrap();
        assert!(!paths.nautilus_script.exists());
        assert!(!paths.dolphin_service_menu.exists());
        assert!(
            !fs::read_to_string(&paths.thunar_uca)
                .unwrap()
                .contains(THUNAR_UNIQUE_ID)
        );
        let _ = fs::remove_dir_all(&root);
    }
}
